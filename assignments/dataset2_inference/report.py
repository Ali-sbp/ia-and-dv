"""Reproduce the Russian Dataset 2 report from the two course Parquet files."""

import argparse
from pathlib import Path

from analysis import BASELINE, DATA, DEFAULT_COST, HERE, cutoff, decimal, integer, load, percent


def format_point(title, p, k):
    cells = [title, cutoff(p.threshold), *map(integer, (p.tp, p.fp, p.fn, p.tn)),
             percent(p.precision), percent(p.recall), decimal(p.fbeta(k), 4), integer(p.cost(k))]
    return "| " + " | ".join(cells) + " |"


def render(log):
    k = DEFAULT_COST
    baseline = log.sweep.at(BASELINE)
    cost_best, f_best = log.sweep.best(k)
    rows = "\n".join(format_point(title, p, k) for title, p in (
        ("Учебный порог", baseline), ("Минимум стоимости", cost_best), ("Максимум F₂", f_best)
    ))
    scenario_rows = []
    for n in [2, 3, 4, 5, 8, 10]:
        a, b = log.sweep.best(n)
        scenario_rows.append(f"| {n} | {cutoff(a.threshold)} | {integer(a.fp)} | {integer(a.fn)} | "
                             f"{integer(a.cost(n))} | {cutoff(b.threshold)} | {integer(b.cost(n))} |")
    scenarios = "\n".join(scenario_rows)
    return f"""# Датасет 2 — инференс модели СОК (ML-трек)

## Цель и данные

Отчёт для руководителя смены СОК и аналитика, который оценивает правила эскалации. Цель — показать, как порог модельной оценки меняет нагрузку очереди и число пропусков инцидентов. Это анализ **сохранённых предсказаний** учебной модели; модель здесь не переобучается и не выполняет новый инференс.

Источник — учебный комплект практики 3.6: `MODEL_PREDICTIONS_target.parquet` и `iavd_incidents_raw3_target.parquet`. Всего **{integer(log.total)} прогнозов**, в метрики включены **{integer(len(log.labeled))}** с `y ∈ {{0, 1}}`: **{integer(baseline.tp + baseline.fn)} инцидентов** и **{integer(baseline.fp + baseline.tn)} легитимных случаев**. Не размечены {integer(log.missing_label)}, исключены по специальным меткам {integer(log.excluded_label)}. У {integer(log.no_matching_card)} записей лога нет строки в парной таблице карточек. Метрики считаются по бинарной разметке, а карточки присоединяются по `incident_id` для примеров, без удаления размеченных записей.

Положительный класс — **инцидент** (`y = 1`). Предсказываем инцидент, если `y_pred_proba ≥ τ`. Учебный порог **0,18** относится к оценке инцидента; **0,82** в параметрах модели относится к противоположному классу. Полнота (recall) показывает, какую долю инцидентов нашли; точность положительных прогнозов (precision) — какая доля выданных тревог действительно относится к инцидентам. Эти две метрики показывают цену изменения порога для покрытия и нагрузки.

## 3.2, задание 1 — матрица стоимости

| Фактический класс | Прогноз «инцидент» | Прогноз «легитимно» |
| --- | --- | --- |
| Инцидент | TP: инцидент отправлен на проверку, 0 | FN: пропуск, расследование задерживается, **{k}** |
| Легитимно | FP: лишняя проверка и время аналитика, **1** | TN: лишней проверки нет, 0 |

- За единицу принимаем условную стоимость проверки одной ложной тревоги; денежных оценок нет.
- В рабочем сценарии берём **k = {k}**: один пропуск условно стоит четырёх лишних проверок. Это допущение для сравнения режимов, а не измеренная цена ошибки.
- В реальном СОК отношение определяет руководитель СОК вместе с владельцем рисков, с учётом нагрузки смены и последствий пропуска.
- Проверяем устойчивость при **k от 2 до 10**: при более дорогом пропуске допустимо принять больше тревог, чтобы повысить полноту.

## 3.2, задание 2 — сравнение порогов

`Cost(τ) = k × FN + FP`. Для `β = √k = 2` сравниваем со значением `F₂ = 5TP / (5TP + 4FN + FP)`. Перебираем все уникальные оценки и границы 0/1. Прогноз меняется только при пересечении оценки; равные оценки обрабатываем вместе. Среди равных оптимумов берём самый высокий порог из проверенных (меньше тревог). Расчёт выполнен на всей размеченной части лога.

| Режим | Порог τ | TP | FP | FN | TN | Precision | Recall | F₂ | Стоимость |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
{rows}

**Почему пороги различаются.** Максимум F₂ даёт на **{integer(f_best.tp - cost_best.tp)}** найденных инцидента больше, но добавляет **{integer(f_best.fp - cost_best.fp)}** ложных тревог. При k = {k} эти найденные инциденты экономят **{integer(k * (cost_best.fn - f_best.fn))}** условных единиц, а ложные тревоги стоят **{integer(f_best.fp - cost_best.fp)}**. Поэтому F₂ выигрывает по своему критерию, но стоит на **{integer(f_best.cost(k) - cost_best.cost(k))}** единицу больше. F₂ оценивает соотношение верных обнаружений и ошибок, тогда как Cost суммирует потери.

**Рекомендация для этого сценария:** взять **τ = {cutoff(cost_best.threshold)}** как кандидата для проверки при k = {k}. Относительно 0,18 он убирает **{integer(baseline.fp - cost_best.fp)}** ложных тревог ценой **{integer(cost_best.fn - baseline.fn)}** дополнительных пропусков и снижает расчётную стоимость на **{integer(baseline.cost(k) - cost_best.cost(k))}** единиц. Если у команды есть обязательный минимум полноты или другой бюджет очереди, порог надо подбирать с этим ограничением. Разница между двумя оптимумами мала; перед рабочим применением проверим выбор на другом временном срезе и согласуем k с руководителем СОК.

## Чувствительность к цене пропуска

| k | Порог min Cost | FP при min Cost | FN при min Cost | min Cost | Порог max Fβ | Cost при max Fβ |
| ---: | ---: | ---: | ---: | ---: | ---: | ---: |
{scenarios}

При k = 2 выгоднее строже ограничить очередь; при k = 5 цели совпадают на одном пороге. При k = 8 и 10 максимум Fβ выбирает более низкий порог, чем минимум условной стоимости. Стоимости из разных строк нельзя сравнивать как один денежный показатель, поскольку меняется оценка FN.

В [приложении](README.md) можно менять τ и k, сравнивать три режима, читать матрицу ошибок и просматривать карточки FP/FN рядом с выбранным порогом. Оптимум найден и оценён на одном учебном логе; это демонстрация, а не независимая валидация качества модели.

## Источники

[Материалы курса](https://disk.yandex.ru/d/waiZmiOzun8EZA): 3.1 «Метрики», задание 1; 3.2 «Матрица ошибок», опорный конспект, §9; практика 3.6, README и словарь полей учебного комплекта.
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=DATA)
    parser.add_argument("--output", type=Path, default=HERE / "ОТЧЁТ.md")
    args = parser.parse_args()
    args.output.write_text(render(load(args.data_dir)), encoding="utf-8")
